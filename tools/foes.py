# builds zanko/assets/foes.png + zanko/js/foe_atlas.js from the enemy sheet (magenta background, 4x2: base poses on top, variants below)
import sys,json,numpy as np
from PIL import Image,ImageFilter,ImageDraw
from scipy import ndimage as ndi
SRC='/mnt/user-data/uploads/6f8b487e-image.png'; OUT='/home/claude/zanko/'; PPU=10.0
TYPES=[('dummy',30),('patrol',15),('heavy',32),('turret',18)]      # drawn height in world units (hit boxes: 30, 16, 30, 18)
im=np.array(Image.open(SRC).convert('RGB')).astype(np.int32); H,W=im.shape[:2]
def key(cell):
    bg=np.median(np.concatenate([cell[:6].reshape(-1,3),cell[-6:].reshape(-1,3)]),axis=0)
    d=np.sqrt(((cell-bg)**2).sum(2)); near=d<95
    lab,_=ndi.label(near); edge=set(lab[0])|set(lab[-1])|set(lab[:,0])|set(lab[:,-1]); edge.discard(0)
    bgm=np.isin(lab,list(edge)); a=np.where(bgm,0,255).astype(np.uint8)
    a=np.array(Image.fromarray(a).filter(ImageFilter.GaussianBlur(0.7))); a=np.where(bgm&(a<128),0,a)
    rgb=cell.copy(); r,g,b=rgb[...,0],rgb[...,1],rgb[...,2]
    band=ndi.binary_dilation(bgm,iterations=3)&~bgm                 # pixels next to the background carry a magenta fringe
    spill=band&(np.abs(r-b)<70)&(np.minimum(r,b)-g>35)
    rgb[...,0]=np.where(spill,g+6,r); rgb[...,2]=np.where(spill,g+12,b)
    rg=np.dstack([np.clip(rgb,0,255).astype(np.uint8),a])
    lab,n=ndi.label(a>40)
    if n>1:
        sz=ndi.sum(np.ones_like(lab),lab,range(1,n+1)); rg[...,3]=np.where(lab==1+int(np.argmax(sz)),rg[...,3],0)
    return rg,int(spill.sum())
cells=[key(im[r*H//2:(r+1)*H//2,c*W//4:(c+1)*W//4]) for r in range(2) for c in range(4)]
def box(rg): ys,xs=np.nonzero(rg[...,3]>128); return xs.min(),xs.max()+1,ys.min(),ys.max()+1
def basemid(rg):
    al=rg[...,3]>128; bot=np.nonzero(al.any(1))[0].max(); x=np.nonzero(al[bot-7:bot+1].any(0))[0]; return (x.min()+x.max())/2
items=[]; rep={}
for i,(name,units) in enumerate(TYPES):
    a,b=cells[i][0],cells[i+4][0]; x0,x1,y0,y1=box(a); sc=units*PPU/(y1-y0)
    ax=basemid(a) if name!='patrol' else (x0+x1)/2
    rep[name]={'src_h':int(y1-y0),'src_w':int(x1-x0),'scale':round(sc,3),'spill_px':[cells[i][1],cells[i+4][1]]}
    for k,rg in enumerate((a,b)):
        bx0,bx1,by0,by1=box(rg); p=Image.fromarray(rg[by0:by1,bx0:bx1],'RGBA'); w,h=round(p.width*sc),round(p.height*sc); p=p.resize((w,h),Image.LANCZOS)
        items.append((f'{name}{k}',p,{'w':w,'h':h,'ax':round((ax-bx0)*sc,1),'ay':h}))
x=0; pad=2; Hh=max(d['h'] for _,_,d in items); atlas=Image.new('RGBA',(sum(d['w']+pad for _,_,d in items),Hh),(0,0,0,0))
for n,p,d in items: d['x'],d['y']=x,0; atlas.alpha_composite(p,(x,0)); x+=d['w']+pad
atlas.quantize(colors=128,method=Image.Quantize.FASTOCTREE,dither=Image.Dither.NONE).save(OUT+'assets/foes.png',optimize=True)
open(OUT+'js/foe_atlas.js','w').write('// generated by tools/foes.py from the enemy sheet: do not edit by hand\nconst FOE_ATLAS = '+json.dumps({'ppu':PPU,'frames':{n:d for n,p,d in items}},separators=(',',':'))+';\n')
chk=Image.new('RGB',(atlas.width,atlas.height+20),(11,19,36)); chk.paste(atlas,(0,0),atlas); chk.save('/home/claude/gen15/out/foes_check.png')
print(atlas.size,json.dumps(rep))
