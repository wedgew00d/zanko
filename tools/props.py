# builds zanko/assets/props.png + zanko/js/prop_atlas.js from the equipment sheet (magenta background, 4x2)
import json,numpy as np
from PIL import Image,ImageFilter
from scipy import ndimage as ndi
SRC='/mnt/user-data/uploads/2624ea1e-image.png'; OUT='/home/claude/zanko/'; PPU=10.0
# name, cell index, drawn height in world units, cell whose height sets the scale (pairs share one scale)
ITEMS=[('term',0,34,0),('switch0',1,30,1),('switch1',5,30,1),('heal0',2,28,2),('heal1',6,28,2),('check0',3,37,3),('check1',7,37,3),('goal',4,54,4)]
im=np.array(Image.open(SRC).convert('RGB')).astype(np.int32); H,W=im.shape[:2]
def key(cell):
    # magenta is keyed by colour everywhere (not only where it touches the border): the capsule's inside is enclosed
    bg=np.median(np.concatenate([cell[:6].reshape(-1,3),cell[-6:].reshape(-1,3)]),axis=0)
    bgm=np.sqrt(((cell-bg)**2).sum(2))<95
    lab,_=ndi.label(bgm); edge=set(lab[0])|set(lab[-1])|set(lab[:,0])|set(lab[:,-1]); edge.discard(0); outer=np.isin(lab,list(edge)); inner=bgm&~outer
    a=np.where(bgm,0,255).astype(np.uint8); a=np.array(Image.fromarray(a).filter(ImageFilter.GaussianBlur(0.7))); a=np.where(bgm&(a<128),0,a)
    rgb=cell.copy(); r,g,b=rgb[...,0],rgb[...,1],rgb[...,2]
    band=ndi.binary_dilation(bgm,iterations=3)&~bgm; spill=band&(np.abs(r-b)<70)&(np.minimum(r,b)-g>35)
    rgb[...,0]=np.where(spill,g-8,r); rgb[...,2]=np.where(spill,g+14,b)
    rg=np.dstack([np.clip(rgb,0,255).astype(np.uint8),a])
    lab,n=ndi.label(a>40)
    if n>1:
        sz=ndi.sum(np.ones_like(lab),lab,range(1,n+1)); keep=[k+1 for k in range(n) if sz[k]>400]; rg[...,3]=np.where(np.isin(lab,keep),rg[...,3],0)
    return rg,inner
cells=[key(im[r*H//2:(r+1)*H//2,c*W//4:(c+1)*W//4]) for r in range(2) for c in range(4)]
def box(m): ys,xs=np.nonzero(m); return int(xs.min()),int(xs.max())+1,int(ys.min()),int(ys.max())+1
def basemid(al):
    bot=np.nonzero(al.any(1))[0].max(); x=np.nonzero(al[bot-7:bot+1].any(0))[0]; return (x.min()+x.max())/2
items=[]
for name,ci,units,ref in ITEMS:
    rg,inner=cells[ci]; al=rg[...,3]>128; x0,x1,y0,y1=box(al); rx0,rx1,ry0,ry1=box(cells[ref][0][...,3]>128); sc=units*PPU/(ry1-ry0)
    ax=basemid(al); ay=y1; p=Image.fromarray(rg[y0:y1,x0:x1],'RGBA'); w,h=round(p.width*sc),round(p.height*sc); p=p.resize((w,h),Image.LANCZOS)
    d={'w':w,'h':h,'ax':round((ax-x0)*sc,1),'ay':h}
    U=lambda px,py:[round((px-ax)*sc/PPU,2),round((py-ay)*sc/PPU,2)]      # cell pixels -> world units from the anchor
    r,g,b=[rg[...,i].astype(int) for i in range(3)]
    if name=='term':                                                      # the dark screen: the game lights it
        m=al&(r<40)&(g<40)&(b<55); lab,n=ndi.label(m); sz=ndi.sum(m,lab,range(1,n+1)); bx=box(lab==1+int(np.argmax(sz)))
        p0,p1=U(bx[0],bx[2]),U(bx[1],bx[3]); d['rect']=[p0[0],p0[1],round(p1[0]-p0[0],2),round(p1[1]-p0[1],2)]
    if name.startswith('switch'):                                         # the lamp
        m=al&((r>220)&(g>150)&(b<120) if name=='switch0' else (g>220)&(b>220)&(r>120)); lab,n=ndi.label(m); sz=ndi.sum(m,lab,range(1,n+1)); ys,xs=np.nonzero(lab==1+int(np.argmax(sz))); d['lamp']=U(xs.mean(),ys.mean())
    if name.startswith('heal'):                                           # the see-through inside of the tube
        lab,n=ndi.label(inner); sz=ndi.sum(inner,lab,range(1,n+1)); bx=box(lab==1+int(np.argmax(sz))); p0,p1=U(bx[0],bx[2]),U(bx[1],bx[3]); d['rect']=[p0[0],p0[1],round(p1[0]-p0[0],2),round(p1[1]-p0[1],2)]
    if name.startswith('check'):                                          # the sign on top
        top=al.copy(); top[y0+int((y1-y0)*0.36):]=False; ys,xs=np.nonzero(top); d['lamp']=U(xs.mean(),ys.mean())
    items.append((name,p,d))
x=0; pad=2; Hh=max(d['h'] for _,_,d in items); atlas=Image.new('RGBA',(sum(d['w']+pad for _,_,d in items),Hh),(0,0,0,0))
for n,p,d in items: d['x'],d['y']=x,0; atlas.alpha_composite(p,(x,0)); x+=d['w']+pad
atlas.quantize(colors=128,method=Image.Quantize.FASTOCTREE,dither=Image.Dither.NONE).save(OUT+'assets/props.png',optimize=True)
open(OUT+'js/prop_atlas.js','w').write('// generated by tools/props.py from the equipment sheet: do not edit by hand\nconst PROP_ATLAS = '+json.dumps({'ppu':PPU,'frames':{n:d for n,p,d in items}},separators=(',',':'))+';\n')
chk=Image.new('RGB',(atlas.width,atlas.height+10),(11,19,36)); chk.paste(atlas,(0,0),atlas); chk.save('/home/claude/gen15/out/props_check.png')
print(atlas.size); print(json.dumps({n:{k:v for k,v in d.items() if k in('rect','lamp','w','h')} for n,p,d in items}))
